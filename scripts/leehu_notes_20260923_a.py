def _josa(text: str, consonant: str, vowel: str) -> str:
    """Append the correct Korean particle for the final syllable."""
    last = next((char for char in reversed(text) if "가" <= char <= "힣"), text[-1])
    has_final = "가" <= last <= "힣" and (ord(last) - ord("가")) % 28 != 0
    return f"{text}{consonant if has_final else vowel}"


def _object(text: str) -> str:
    return _josa(text, "을", "를")


def _subject(text: str) -> str:
    return _josa(text, "이", "가")


def _topic(text: str) -> str:
    return _josa(text, "은", "는")


def _with(text: str) -> str:
    return _josa(text, "과", "와")


def _direction(text: str) -> str:
    last = text[-1]
    if "가" <= last <= "힣":
        final = (ord(last) - ord("가")) % 28
        return f"{text}{'으로' if final not in (0, 8) else '로'}"
    return f"{text}로"


def _quoted_topic(text: str) -> str:
    particle = _topic(text)[len(text):]
    return f"『{text}』{particle}"


