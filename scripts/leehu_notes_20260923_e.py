def _particle(word: str, consonant: str, vowel: str) -> str:
    """마지막 한글 음절의 받침 유무에 맞는 조사를 붙인다."""
    last = next((char for char in reversed(word) if "가" <= char <= "힣"), "")
    jongseong = (ord(last) - ord("가")) % 28 if last else 0
    if (consonant, vowel) == ("으로", "로") and jongseong == 8:
        return word + vowel
    return word + (consonant if jongseong else vowel)


